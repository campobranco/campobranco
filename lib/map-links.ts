export interface MapLinkInput {
    lat?: number | string | null;
    lng?: number | string | null;
    address?: string | null;
    cityName?: string | null;
}

export interface ResolveNavigationLinksInput extends MapLinkInput {
    googleMapsLink?: string | null;
    wazeLink?: string | null;
}

function normalizeForComparison(text: string): string {
    return text
        .normalize('NFD')
        .replace(/[\u0300-\u036f]/g, '')
        .toLowerCase()
        .trim();
}

/**
 * Monta a string de busca de endereço acrescentando a cidade quando ela ainda não está presente.
 */
export function formatAddressQuery(address?: string | null, cityName?: string | null): string {
    const cleanAddress = (address || '').replace(/\s+/g, ' ').trim();
    if (!cleanAddress) {
        return '';
    }

    const cleanCity = (cityName || '').replace(/\s+/g, ' ').trim();
    if (!cleanCity || cleanCity === '...') {
        return cleanAddress;
    }

    if (normalizeForComparison(cleanAddress).includes(normalizeForComparison(cleanCity))) {
        return cleanAddress;
    }

    return `${cleanAddress}, ${cleanCity}`;
}

/**
 * Valida coordenadas geográficas ignorando valores vazios ou (0, 0).
 */
export function hasValidCoordinates(
    lat?: number | string | null,
    lng?: number | string | null
): { lat: number; lng: number } | null {
    if (lat === null || lat === undefined || lat === '' || lng === null || lng === undefined || lng === '') {
        return null;
    }

    const parsedLat = typeof lat === 'number' ? lat : parseFloat(lat);
    const parsedLng = typeof lng === 'number' ? lng : parseFloat(lng);

    if (!Number.isFinite(parsedLat) || !Number.isFinite(parsedLng)) {
        return null;
    }
    if (parsedLat === 0 && parsedLng === 0) {
        return null;
    }
    if (parsedLat < -90 || parsedLat > 90 || parsedLng < -180 || parsedLng > 180) {
        return null;
    }

    return { lat: parsedLat, lng: parsedLng };
}

/**
 * Extrai coordenadas de URLs completas do Google Maps (!3d...!4d..., @lat,lng, q/query=lat,lng)
 * ou do Waze (ll=lat,lng). Retorna null para links curtos sem coordenadas na URL.
 */
export function extractCoordsFromMapUrl(url?: string | null): { lat: number; lng: number } | null {
    const clean = (url || '').trim();
    if (!clean) return null;

    const match =
        clean.match(/!3d(-?\d{1,2}\.\d+)!4d(-?\d{1,3}\.\d+)/) ||
        clean.match(/@(-?\d{1,2}\.\d+),(-?\d{1,3}\.\d+)/) ||
        clean.match(/[?&](?:q|query|ll)=(-?\d{1,2}\.\d+),(-?\d{1,3}\.\d+)/);

    if (!match) return null;
    return hasValidCoordinates(match[1], match[2]);
}

/**
 * Gera link direto do Waze com navegação automática (prioriza coordenadas exatas).
 */
export function buildWazeLink(input: MapLinkInput): string {
    const coords = hasValidCoordinates(input.lat, input.lng);
    if (coords) {
        return `https://waze.com/ul?ll=${coords.lat},${coords.lng}&navigate=yes`;
    }

    const query = formatAddressQuery(input.address, input.cityName);
    if (query) {
        return `https://waze.com/ul?q=${encodeURIComponent(query)}&navigate=yes`;
    }

    return '';
}

/**
 * Gera link oficial de busca/localização do Google Maps (prioriza coordenadas exatas).
 */
export function buildGoogleMapsLink(input: MapLinkInput): string {
    const coords = hasValidCoordinates(input.lat, input.lng);
    if (coords) {
        return `https://www.google.com/maps/search/?api=1&query=${coords.lat},${coords.lng}`;
    }

    const query = formatAddressQuery(input.address, input.cityName);
    if (query) {
        return `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(query)}`;
    }

    return '';
}

export function isAutoGeneratedWazeLink(url?: string | null): boolean {
    return (url || '').trim().startsWith('https://waze.com/ul?');
}

export function isAutoGeneratedGoogleMapsLink(url?: string | null): boolean {
    return (url || '').trim().startsWith('https://www.google.com/maps/search/?api=1&query=');
}

/**
 * Preserva links preenchidos manualmente e gera automaticamente os campos vazios.
 */
export function resolveNavigationLinks(input: ResolveNavigationLinksInput): {
    googleMapsLink: string;
    wazeLink: string;
} {
    const manualGoogle = (input.googleMapsLink || '').trim();
    const manualWaze = (input.wazeLink || '').trim();

    return {
        googleMapsLink: manualGoogle || buildGoogleMapsLink(input),
        wazeLink: manualWaze || buildWazeLink(input),
    };
}
